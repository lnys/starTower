// Run from any directory to synchronize Flutter's style catalog with Vue.
import { readFileSync, writeFileSync } from 'node:fs';
const styles = JSON.parse(readFileSync(new URL('../../design/styles.json', import.meta.url)));
const color = (hex) => `Color(0xff${hex})`;
const rows = styles.map(({id, name, bg, panel, button, accent, muted, trim, radius}) =>
  `  TowerStyle(\n    '${id}',\n    '${name}',\n${[bg, panel, button, accent, muted, trim].map((hex) => `    ${color(hex)},`).join('\n')}\n    ${radius},\n  ),`
).join('\n');
writeFileSync(new URL('../lib/ui/style_catalog.dart', import.meta.url), `// Generated by tool/generate_styles.mjs. Edit design/styles.json instead.
import 'package:flutter/material.dart';

class TowerStyle {
  final String id, name;
  final Color background, panel, button, accent, muted, trim;
  final double radius;

  const TowerStyle(this.id, this.name, this.background, this.panel, this.button,
      this.accent, this.muted, this.trim, this.radius);

  bool get classic => id == 'classic';
  bool get pixel => id == 'pixel';
}

const towerStyles = [
${rows}
];

TowerStyle resolveTowerStyle(String? id) =>
    towerStyles.firstWhere((style) => style.id == id,
        orElse: () => towerStyles.first);
`);
